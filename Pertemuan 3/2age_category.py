age = input("Enter age:")
age = float(age)

if (age >= 71):
    print("Elderly")
elif (age >= 51):
    print("Pre-Elderly")
elif (age >= 31):
    print("Adult")
elif (age >= 22):
    print("Pre-Adult")
elif (age >= 18):
    print("Young Adult")
elif (age >= 13):
    print("Teenager")
elif (age >= 6):
    print("Child")
elif (age >= 4):
    print("Preschooler")
elif (age >= 2):
    print("Toddler")
elif (age >= 0):
    print("Baby")